"""
MVFE PIPELINE METRICS
Records per-run statistics to mvfe_pipeline_stats table for longitudinal analysis.
Provides aggregation queries for the /api/mvfe/stats endpoint.
"""
from __future__ import annotations

import logging
from typing import Any, Optional

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Write path
# ---------------------------------------------------------------------------

def record_pipeline_run(
    db_pool,
    *,
    user_id: str,
    event_id: str,
    pipeline_latency_ms: float,
    formation: dict,
    critic: dict,
    governance: dict,
    emotion: dict,
) -> None:
    """Persist one MVFE pipeline run to mvfe_pipeline_stats.

    Args:
        db_pool: psycopg2 ThreadedConnectionPool
        user_id: authenticated user identifier
        event_id: UUID generated by orchestrator for this run
        pipeline_latency_ms: wall-clock time for full pipeline
        formation: FormationResult as dict
        critic: CriticReport as dict
        governance: GovernanceReport as dict
        emotion: EmotionState as dict
    """
    conn = None
    try:
        conn = db_pool.getconn()
        with conn.cursor() as cur:
            cur.execute(
                """
                INSERT INTO mvfe_pipeline_stats (
                    user_id, event_id, pipeline_latency_ms,
                    formation_score, drift_score, stability_score, formation_score_ema,
                    coherence_score, overfit_risk, confidence_adjustment,
                    governance_passed, governance_violations, governance_risk_level,
                    primary_emotion, emotion_intensity, emotion_uncertainty
                ) VALUES (
                    %s, %s, %s,
                    %s, %s, %s, %s,
                    %s, %s, %s,
                    %s, %s, %s,
                    %s, %s, %s
                )
                ON CONFLICT (event_id) DO NOTHING
                """,
                (
                    user_id,
                    event_id,
                    round(pipeline_latency_ms, 1),
                    # formation
                    formation.get("formation_score", 0.0),
                    formation.get("drift_score", 0.0),
                    formation.get("stability_score", 0.0),
                    formation.get("formation_score_ema", 0.0),
                    # critic
                    critic.get("coherence_score", 0.0),
                    critic.get("overfit_risk", 0.0),
                    critic.get("confidence_adjustment", 0.0),
                    # governance
                    governance.get("passed", True),
                    len(governance.get("violations", [])),
                    governance.get("risk_level", "low"),
                    # emotion
                    emotion.get("primary_emotion", ""),
                    emotion.get("intensity", 0.0),
                    emotion.get("uncertainty", 0.0),
                ),
            )
            conn.commit()
    except Exception as exc:
        if conn:
            try:
                conn.rollback()
            except Exception:
                pass
        logger.warning(f"[mvfe.metrics] record failed: {exc}")
    finally:
        if conn is not None:
            try:
                db_pool.putconn(conn)
            except Exception:
                pass


